    public void update_tabel_popup(String sql) {
        try {
            pst = MySQLConfig.prepareStatement(sql);
            rst = pst.executeQuery();
            tablePenyaluran.setModel(DbUtils.resultSetToTableModel(rst));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

